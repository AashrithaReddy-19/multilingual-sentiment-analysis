"""Write docs/final_report_phase3.md from the saved artifacts only (no numbers are typed by hand).

    python -m pipeline.write_phase3_report
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from pipeline import paths  # noqa: E402
from sentiment_core.labels import MODEL_C_SKIP  # noqa: E402

EXP = paths.MULTI / "experiments"
OUT = paths.APP_ROOT / "docs" / "final_report_phase3.md"


def f4(v) -> str:
    return "—" if v is None or (isinstance(v, float) and pd.isna(v)) else f"{v:.4f}"


def table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(f4(v) if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(lines)


def main() -> None:
    j = lambda p: json.loads(p.read_text(encoding="utf-8")) if p.exists() else None  # noqa: E731
    clean = j(paths.DATA / "cleaning_report.json")
    comp = pd.read_csv(EXP / "final_model_comparison.csv", encoding="utf-8-sig")
    lb = pd.read_csv(EXP / "experiment_leaderboard.csv", encoding="utf-8-sig")
    stats = j(EXP / "statistical_comparison.json") or {}
    sel = j(paths.MULTI / "final_selection.json") or {}
    trans_dir = EXP / "transformers"
    t_runs = sorted(trans_dir.glob("*/validation_metrics.json")) if trans_dir.exists() else []
    L = ["# Final report — multilingual sentiment (Telugu, English, Telugu-English code-mixed)", "",
         "_Generated by `pipeline.write_phase3_report` from saved artifacts. Every number comes from an executed run._", "",
         "> No real conversation metadata was available, therefore genuine context-aware training was not performed.", ""]

    L += ["## 1. Dataset summary", "", "| Dataset | Language | Rows after cleaning | Label source |", "|---|---|---|---|"]
    lang = {"TeSent": "Telugu", "TweetEval": "English", "CMTET": "Telugu-English code-mixed (Romanized)"}
    src = {"TeSent": "README: Positive/Negative/Neutral", "TweetEval": "mapping.txt (0 neg, 1 neu, 2 pos)",
           "CMTET": "README + RANLP 2021 paper (NEG/NTL/POS)"}
    for k, v in (clean or {}).get("per_dataset", {}).items():
        L.append(f"| {k} | {lang.get(k, '')} | {v['final_rows']:,} | {src.get(k, '')} |")
    L += ["", "Hate-speech files in `Tel_Eng_dataset` were **not** converted into sentiment labels and are not used.", ""]

    L += ["## 2. Data split", ""]
    split = (clean or {}).get("split", {})
    L += [f"- Method: {split.get('method', '')}",
          f"- Sizes: " + ", ".join(f"{k} {v:,}" for k, v in split.get("sizes", {}).items()),
          "- Leakage check: no cleaned text appears in more than one split. The test split is frozen: models, "
          "hyperparameters, ensemble weights, temperature and class offsets are chosen on validation only.", ""]

    L += ["## 3. Models tested", "",
          "- **A** word TF-IDF (1–2-grams, 20k) + Logistic Regression (balanced).",
          "- **A+** word TF-IDF + character `char_wb` (3–5) TF-IDF + Logistic Regression (balanced).",
          "- **Classical search** (177 configs): word / char / union TF-IDF grids; LR, LinearSVC, SGD; preprocessing "
          "variants (casing, repeated characters, emoticon tokens); label-free signal features.",
          "- **Transformers (Colab GPU)**: XLM-RoBERTa base (Model B) with staged tuning (learning rate, loss: CE / weighted "
          "CE / focal, label smoothing, epochs, batch, weight decay, warmup, language tokens), MuRIL, IndicBERTv2, mDeBERTa-v3.",
          "- **Ensemble** of A+ and the best Transformers, weights tuned on validation.",
          f"- **Model C (context-aware)**: {MODEL_C_SKIP}", ""]

    cls = lb[lb["experiment_id"].str.match(r"s[0-6]_")].sort_values("validation_macro_f1", ascending=False)
    L += ["## 4. Classical search result", "",
          f"{len(cls)} configurations were scored on validation only. Top 5:", "",
          table(cls.head(5)[["experiment_id", "model", "validation_accuracy", "validation_macro_precision",
                             "validation_macro_recall", "validation_macro_f1"]]), "",
          "No configuration beat the A+ configuration by a meaningful margin (differences ≤ 0.0002 validation macro F1), "
          "so **A+ remains the best classical model**; the classical phase is closed.", ""]

    L += ["## 5. Transformer experiments", ""]
    if not t_runs:
        L += ["**Not trained / pending GPU run.** The resumable Colab package is ready "
              "(`artifacts/colab_package_phase3/`, instructions in `docs/COLAB_PHASE3.md`). No Transformer result is "
              "reported until a real run is imported.", ""]
    else:
        rows = []
        for f in t_runs:
            v, c = json.loads(f.read_text()), json.loads((f.parent / "config.json").read_text())
            rows.append({"experiment": f.parent.name, "val acc": v["accuracy"], "val macro P": v["macro_precision"],
                         "val macro R": v["macro_recall"], "val macro F1": v["macro_f1"], "val weighted F1": v["weighted_f1"],
                         "Neg F1": v["per_class"]["Negative"]["f1"], "Neu F1": v["per_class"]["Neutral"]["f1"],
                         "Pos F1": v["per_class"]["Positive"]["f1"], "best epoch": float(c["best_epoch"])})
        df = pd.DataFrame(rows).sort_values(["val macro F1", "val macro R", "val acc"], ascending=False)
        L += [f"{len(df)} runs (validation; ranked by macro F1, then macro recall, then accuracy):", "", table(df), ""]

    show = ["Model", "Accuracy", "Macro Precision", "Macro Recall", "Macro F1", "Weighted F1", "Negative F1",
            "Neutral F1", "Positive F1", "English Macro F1", "Telugu Macro F1", "Code-mixed Macro F1",
            "Best Validation Macro F1"]
    L += ["## 6. Final comparison (multilingual test split, n = 15,124)", "",
          table(comp[comp["Macro F1"].notna()][show]), ""]
    for _, r in comp[comp["Macro F1"].isna()].iterrows():
        L.append(f"- **{r['Model']}**: {r['Notes']}")
    imp = EXP / "improvements_over_a_plus.csv"
    if imp.exists():
        L += ["", "Absolute change vs A+:", "", table(pd.read_csv(imp, encoding="utf-8-sig"))]
    L += [""]

    ea = EXP / "error_analysis_model_a_plus"
    pairs = pd.read_csv(ea / "class_pair_errors.csv")
    langs = pd.read_csv(ea / "errors_by_language.csv")
    L += ["## 7. Error analysis", "",
          "A+ test errors by class pair (most involve Neutral):", "", table(pairs), "",
          "A+ by language: " + "; ".join(f"{r.language_type} accuracy {r.accuracy:.4f} ({r.share_of_all_errors:.0%} of errors)"
                                         for r in langs.itertuples()) + ".", ""]
    ch = EXP / "confusion_changes_vs_a_plus.csv"
    if ch.exists():
        L += ["Main confusions, A+ vs Transformer/ensemble (test):", "", table(pd.read_csv(ch, encoding="utf-8-sig")), ""]
    L += ["High-confidence validation mistakes are listed in `experiments/possible_label_ambiguity.csv` "
          "(possible annotation ambiguity; nothing was relabelled). Error categories are heuristic, not ground truth.", ""]

    L += ["## 8. Statistical comparison (same test examples)", "", "| Comparison | McNemar p | Macro F1 diff | 95% bootstrap CI |",
          "|---|---|---|---|"]
    for k, v in stats.items():
        bs = v["bootstrap"]
        L.append(f"| {k} | {v['mcnemar']['p_value']:.3g} | {bs['macro_f1_diff_mean']:+.4f} | "
                 f"[{bs['macro_f1_diff_ci95'][0]:+.4f}, {bs['macro_f1_diff_ci95'][1]:+.4f}] |")
    L += ["", "For a row 'X vs Y' the macro F1 difference is X − Y. A difference counts as meaningful only if "
              "McNemar p < 0.05 and the bootstrap CI excludes 0.", ""]

    L += ["## 9. Calibration", "", "| Model | Mean confidence | ECE (10 bins) | Temperature (fit on validation) | ECE after |",
          "|---|---|---|---|---|"]
    for d in sorted((EXP / "final").iterdir()):
        tm = j(d / "test_metrics.json")
        if tm:
            ts = tm.get("temperature_scaling") or {}
            L.append(f"| {d.name} | {tm['calibration_test']['mean_confidence']:.4f} | {tm['calibration_test']['ece_10_bins']:.4f} | "
                     f"{f4(ts.get('T_fitted_on_validation'))} | {f4(ts.get('test_ece_after'))} |")
    ap = j(EXP / "final" / "model_a_plus" / "test_metrics.json")
    if ap:
        L += ["", "A+ accuracy by confidence bucket (test): " + "; ".join(
            f"{b['bucket']}: {f4(b['accuracy'])} (n={b['n']})" for b in ap["calibration_test"]["buckets"]) + "."]
    L += [""]

    L += ["## 10. Final selected model", ""]
    if sel:
        t = sel["test"]
        L += [f"**{sel['selected_model_name']}** (served as `{sel['served_model_id']}`).", "",
              f"Test: accuracy {t['accuracy']:.4f}, macro precision {t['macro_precision']:.4f}, macro recall "
              f"{t['macro_recall']:.4f}, macro F1 {t['macro_f1']:.4f}, weighted F1 {t['weighted_f1']:.4f}.", "",
              "Selection rule: " + " ".join(sel["rule"].split()), ""] + [f"- {x}" for x in sel["reasoning"]]
        L += ["", f"Target ≥ 0.75 macro F1: **{'ACHIEVED' if t['macro_f1'] >= 0.75 else 'NOT ACHIEVED'}** "
                  f"(actual {t['macro_f1']:.4f})."]
    L += [""]

    L += ["## 11. Limitations", "",
          "- English (TweetEval tweets) dominates the test set and the errors; the Neutral boundary is the main weakness.",
          "- Language type at prediction time is a script/keyword heuristic, not a trained language identifier.",
          "- Datasets differ in domain (literary/news Telugu, tweets, social-media code-mix); scores are not directly "
          "comparable across languages, and the Telugu-only run uses a different test split.",
          "- Some labels are ambiguous (TeSent annotator disagreement; 55 texts with conflicting labels were kept).",
          "- Transformer results depend on a Colab GPU run; until imported, A+ is served.", ""]

    L += ["## 12. Future context-aware Model C", "",
          f"Status: **{MODEL_C_SKIP}** No real conversation metadata was available, therefore genuine context-aware "
          "training was not performed.", "",
          "Ready for real data: `sentiment_core/context.py` builds `[PREVIOUS_2] … [PREVIOUS_1] … [CURRENT] …` from earlier "
          "messages of the same conversation only (sorted by `message_order`, never future messages), and "
          "`train_transformer.py --input-col context_text` trains it — it refuses to run unless real earlier-message "
          "context exists. Required file: `conversations.csv` with `conversation_id, message_order, text, label, "
          "language_type`; splits must be grouped by conversation.", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
